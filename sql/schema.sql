-- =====================================================================
--  Cricbuzz LiveStats - schema.sql  (PostgreSQL 14+)
--
--  Idempotent: safe to run more than once (IF NOT EXISTS / OR REPLACE).
--  Order matters: parent tables before child tables (FK targets first).
--  Run with:  python -m scripts.init_db
-- =====================================================================

-- ---------------------------------------------------------------------
--  TEAMS - national sides
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS teams (
    team_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cricbuzz_team_id  INTEGER      UNIQUE,
    team_name         VARCHAR(100) NOT NULL UNIQUE,
    short_name        VARCHAR(10),
    country           VARCHAR(60)  NOT NULL,
    team_type         VARCHAR(15)  NOT NULL DEFAULT 'international'
                      CHECK (team_type IN ('international', 'domestic', 'franchise')),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
--  VENUES - grounds (capacity needed for Q4, country for Q12)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS venues (
    venue_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cricbuzz_venue_id INTEGER      UNIQUE,
    venue_name        VARCHAR(150) NOT NULL,
    city              VARCHAR(80)  NOT NULL,
    country           VARCHAR(60)  NOT NULL,
    capacity          INTEGER      CHECK (capacity IS NULL OR capacity > 0),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_venue_name_city UNIQUE (venue_name, city)
);

-- ---------------------------------------------------------------------
--  PLAYERS
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS players (
    player_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cricbuzz_player_id INTEGER      UNIQUE,
    full_name          VARCHAR(120) NOT NULL,
    team_id            INTEGER      NOT NULL
                       REFERENCES teams (team_id) ON DELETE RESTRICT,
    playing_role       VARCHAR(20)  NOT NULL
                       CHECK (playing_role IN ('Batsman', 'Bowler',
                                               'All-rounder', 'Wicket-keeper')),
    batting_style      VARCHAR(30),
    bowling_style      VARCHAR(50),
    date_of_birth      DATE         CHECK (date_of_birth > DATE '1900-01-01'),
    source             VARCHAR(10)  NOT NULL DEFAULT 'api'
                       CHECK (source IN ('api', 'seed', 'manual')),
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
--  SERIES - tours / tournaments (Q8)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS series (
    series_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cricbuzz_series_id    INTEGER      UNIQUE,
    series_name           VARCHAR(200) NOT NULL,
    host_country          VARCHAR(60),
    match_type            VARCHAR(10)  NOT NULL
                          CHECK (match_type IN ('Test', 'ODI', 'T20I', 'Mixed')),
    start_date            DATE         NOT NULL,
    end_date              DATE,
    total_matches_planned SMALLINT     CHECK (total_matches_planned > 0),
    source                VARCHAR(10)  NOT NULL DEFAULT 'api'
                          CHECK (source IN ('api', 'seed', 'manual')),
    CONSTRAINT chk_series_dates CHECK (end_date IS NULL OR end_date >= start_date)
);

-- ---------------------------------------------------------------------
--  MATCHES - one row per game; four role-playing FKs to teams
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS matches (
    match_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cricbuzz_match_id INTEGER      UNIQUE,
    series_id         INTEGER      REFERENCES series (series_id) ON DELETE SET NULL,
    match_description VARCHAR(200) NOT NULL,
    match_format      VARCHAR(5)   NOT NULL
                      CHECK (match_format IN ('Test', 'ODI', 'T20I')),
    match_date        DATE         NOT NULL,
    venue_id          INTEGER      NOT NULL REFERENCES venues (venue_id) ON DELETE RESTRICT,
    team1_id          INTEGER      NOT NULL REFERENCES teams (team_id)  ON DELETE RESTRICT,
    team2_id          INTEGER      NOT NULL REFERENCES teams (team_id)  ON DELETE RESTRICT,
    toss_winner_id    INTEGER      REFERENCES teams (team_id) ON DELETE RESTRICT,
    toss_decision     VARCHAR(4)   CHECK (toss_decision IN ('bat', 'bowl')),
    winner_id         INTEGER      REFERENCES teams (team_id) ON DELETE RESTRICT,
    victory_margin    SMALLINT     CHECK (victory_margin IS NULL OR victory_margin > 0),
    victory_type      VARCHAR(10)
                      CHECK (victory_type IN ('runs', 'wickets', 'innings',
                                              'tie', 'draw', 'no result')),
    match_status      VARCHAR(10)  NOT NULL DEFAULT 'Completed'
                      CHECK (match_status IN ('Upcoming', 'Live',
                                              'Completed', 'Abandoned')),
    source            VARCHAR(10)  NOT NULL DEFAULT 'api'
                      CHECK (source IN ('api', 'seed', 'manual')),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT chk_distinct_teams CHECK (team1_id <> team2_id),
    CONSTRAINT chk_toss_team      CHECK (toss_winner_id IS NULL
                                         OR toss_winner_id IN (team1_id, team2_id)),
    CONSTRAINT chk_toss_pair      CHECK ((toss_winner_id IS NULL) = (toss_decision IS NULL)),
    CONSTRAINT chk_winner_team    CHECK (winner_id IS NULL
                                         OR winner_id IN (team1_id, team2_id)),
    CONSTRAINT chk_completed_has_result
                                  CHECK (match_status <> 'Completed'
                                         OR victory_type IS NOT NULL)
);

-- ---------------------------------------------------------------------
--  BATTING INNINGS - one row per batter per innings (associative table)
--  innings_no is the MATCH innings (1-4), not the team's innings.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS batting_innings (
    batting_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id         INTEGER  NOT NULL REFERENCES matches (match_id) ON DELETE CASCADE,
    player_id        INTEGER  NOT NULL REFERENCES players (player_id) ON DELETE RESTRICT,
    team_id          INTEGER  NOT NULL REFERENCES teams (team_id)    ON DELETE RESTRICT,
    innings_no       SMALLINT NOT NULL CHECK (innings_no BETWEEN 1 AND 4),
    batting_position SMALLINT NOT NULL CHECK (batting_position BETWEEN 1 AND 11),
    runs             SMALLINT NOT NULL DEFAULT 0 CHECK (runs >= 0),
    balls_faced      SMALLINT NOT NULL DEFAULT 0 CHECK (balls_faced >= 0),
    fours            SMALLINT NOT NULL DEFAULT 0 CHECK (fours >= 0),
    sixes            SMALLINT NOT NULL DEFAULT 0 CHECK (sixes >= 0),
    is_out           BOOLEAN  NOT NULL DEFAULT TRUE,
    dismissal        VARCHAR(100),
    strike_rate      NUMERIC(6, 2) GENERATED ALWAYS AS (
                         CASE WHEN balls_faced > 0
                              THEN ROUND(runs * 100.0 / balls_faced, 2) END
                     ) STORED,

    CONSTRAINT uq_bat_player_innings   UNIQUE (match_id, innings_no, player_id),
    CONSTRAINT uq_bat_position_innings UNIQUE (match_id, innings_no, batting_position),
    CONSTRAINT chk_boundaries_le_runs  CHECK (fours * 4 + sixes * 6 <= runs)
);

-- ---------------------------------------------------------------------
--  BOWLING INNINGS - balls_bowled is the source of truth; overs/economy
--  are generated so they can never disagree with it.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS bowling_innings (
    bowling_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id       INTEGER  NOT NULL REFERENCES matches (match_id) ON DELETE CASCADE,
    player_id      INTEGER  NOT NULL REFERENCES players (player_id) ON DELETE RESTRICT,
    team_id        INTEGER  NOT NULL REFERENCES teams (team_id)    ON DELETE RESTRICT,
    innings_no     SMALLINT NOT NULL CHECK (innings_no BETWEEN 1 AND 4),
    balls_bowled   SMALLINT NOT NULL CHECK (balls_bowled >= 0),
    maidens        SMALLINT NOT NULL DEFAULT 0 CHECK (maidens >= 0),
    runs_conceded  SMALLINT NOT NULL DEFAULT 0 CHECK (runs_conceded >= 0),
    wickets        SMALLINT NOT NULL DEFAULT 0 CHECK (wickets BETWEEN 0 AND 10),
    overs          NUMERIC(4, 1) GENERATED ALWAYS AS (
                       (balls_bowled / 6) + (balls_bowled % 6) / 10.0
                   ) STORED,
    economy        NUMERIC(5, 2) GENERATED ALWAYS AS (
                       CASE WHEN balls_bowled > 0
                            THEN ROUND(runs_conceded * 6.0 / balls_bowled, 2) END
                   ) STORED,

    CONSTRAINT uq_bowl_player_innings UNIQUE (match_id, innings_no, player_id)
);

-- ---------------------------------------------------------------------
--  PLAYER FORMAT STATS - career snapshot per format (from API / seed)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS player_format_stats (
    player_id           INTEGER     NOT NULL
                        REFERENCES players (player_id) ON DELETE CASCADE,
    match_format        VARCHAR(5)  NOT NULL
                        CHECK (match_format IN ('Test', 'ODI', 'T20I')),
    matches             SMALLINT    NOT NULL DEFAULT 0 CHECK (matches >= 0),
    innings             SMALLINT    NOT NULL DEFAULT 0 CHECK (innings >= 0),
    runs                INTEGER     NOT NULL DEFAULT 0 CHECK (runs >= 0),
    highest_score       SMALLINT    CHECK (highest_score >= 0),
    batting_average     NUMERIC(6, 2),
    batting_strike_rate NUMERIC(6, 2),
    hundreds            SMALLINT    NOT NULL DEFAULT 0 CHECK (hundreds >= 0),
    fifties             SMALLINT    NOT NULL DEFAULT 0 CHECK (fifties >= 0),
    balls_bowled        INTEGER     NOT NULL DEFAULT 0 CHECK (balls_bowled >= 0),
    wickets             SMALLINT    NOT NULL DEFAULT 0 CHECK (wickets >= 0),
    bowling_average     NUMERIC(6, 2),
    economy             NUMERIC(5, 2),
    catches             SMALLINT    NOT NULL DEFAULT 0 CHECK (catches >= 0),
    stumpings           SMALLINT    NOT NULL DEFAULT 0 CHECK (stumpings >= 0),
    last_updated        TIMESTAMPTZ NOT NULL DEFAULT now(),

    PRIMARY KEY (player_id, match_format)
);

-- ---------------------------------------------------------------------
--  INGESTION LOG - one row per data load (API, seed or manual)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ingestion_log (
    log_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source       VARCHAR(10)  NOT NULL CHECK (source IN ('api', 'seed', 'manual')),
    endpoint     VARCHAR(200),
    records      INTEGER      NOT NULL DEFAULT 0,
    status       VARCHAR(10)  NOT NULL CHECK (status IN ('success', 'partial', 'failed')),
    message      TEXT,
    started_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    finished_at  TIMESTAMPTZ
);

-- =====================================================================
--  INDEXES - PostgreSQL does NOT index foreign keys automatically.
--  (PKs and UNIQUE constraints already have indexes.)
-- =====================================================================
CREATE INDEX IF NOT EXISTS idx_players_team        ON players (team_id);
CREATE INDEX IF NOT EXISTS idx_players_role        ON players (playing_role);

CREATE INDEX IF NOT EXISTS idx_matches_date        ON matches (match_date DESC);
CREATE INDEX IF NOT EXISTS idx_matches_format_date ON matches (match_format, match_date);
CREATE INDEX IF NOT EXISTS idx_matches_venue       ON matches (venue_id);
CREATE INDEX IF NOT EXISTS idx_matches_team1       ON matches (team1_id);
CREATE INDEX IF NOT EXISTS idx_matches_team2       ON matches (team2_id);
CREATE INDEX IF NOT EXISTS idx_matches_winner      ON matches (winner_id);
CREATE INDEX IF NOT EXISTS idx_matches_series      ON matches (series_id);

CREATE INDEX IF NOT EXISTS idx_bat_player_match    ON batting_innings (player_id, match_id);
CREATE INDEX IF NOT EXISTS idx_bat_team            ON batting_innings (team_id);
CREATE INDEX IF NOT EXISTS idx_bowl_player_match   ON bowling_innings (player_id, match_id);
CREATE INDEX IF NOT EXISTS idx_bowl_team           ON bowling_innings (team_id);

CREATE INDEX IF NOT EXISTS idx_series_start        ON series (start_date);

-- =====================================================================
--  TRIGGER - keep updated_at current on every UPDATE
--  (a DEFAULT only fires on INSERT; without this, updated_at goes stale)
-- =====================================================================
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE TRIGGER trg_players_updated_at
    BEFORE UPDATE ON players
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE OR REPLACE TRIGGER trg_matches_updated_at
    BEFORE UPDATE ON matches
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
